"""通道 C：用临时 Chrome 扩展在**原始 profile** 内读取明文 cookies。

为什么需要它：Chrome 127+ 的 App-Bound Encryption（v20）把 cookie 加密绑定到
原 profile 环境。yt-dlp 解不开；复制 profile / 目录联接后 Chrome 自己也会丢弃
v20 cookie；CDP 又受"默认 user-data-dir 拒绝调试端口"与 Origin 策略限制。

本脚本绕开所有限制：用 --load-extension 在用户**原来的 user-data-dir** 里临时
加载一个最小扩展，扩展调用 chrome.cookies.getAll()（由 Chrome 内部解密，拿到的是
明文），POST 回本机临时 HTTP 服务，脚本再写成 Netscape cookies.txt。

- 不需要远程调试端口、不需要手动装扩展
- 扩展只在本次启动通过命令行加载，Chrome 正常重启后不会残留
- Chrome 137+ 默认禁用 --load-extension，脚本会带
  --disable-features=DisableLoadExtensionCommandLineSwitch 放行
- 脚本会关闭并重新启动 Chrome（会恢复标签页），只导出 YouTube/Google 相关 cookie
- 不打印任何 cookie 值

用法：
  python tools/export_chrome_cookies_extension.py --verify
  python tools/export_chrome_cookies_extension.py --profile "Profile 12" --verify
"""
from __future__ import annotations

import argparse
import http.server
import json
import os
import pathlib
import shutil
import sqlite3
import subprocess
import sys
import tempfile
import threading
import time

BASE_DIR = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUT = BASE_DIR / "data" / "cookies.txt"
KEEP_DOMAIN_KEYWORDS = (
    "youtube", "googlevideo", "ytimg", "google", "gstatic", "googleapis",
    "youtube-nocookie", "doubleclick",
)
# 登录态标志（只用于判断，不打印值）
LOGIN_COOKIE_HINTS = (
    "SAPISID", "1PSID", "3PSID", "APISID", "HSID", "SSID",
    "SIDCC", "LOGIN_INFO", "__Secure-1PAPISID",
)

MANIFEST = {
    "manifest_version": 3,
    "name": "Music API Cookie Exporter (temporary)",
    "version": "1.0",
    "description": "Temporary local helper that exports YouTube cookies to the local API.",
    "permissions": ["cookies"],
    "host_permissions": ["<all_urls>"],
    "background": {"service_worker": "sw.js"},
}

SW_TEMPLATE = """
// 临时扩展：由 tools/export_chrome_cookies_extension.py 生成，用完即弃
const ENDPOINT = "__ENDPOINT__";
async function push() {
  try {
    const cookies = await chrome.cookies.getAll({});
    await fetch(ENDPOINT, {
      method: "POST",
      headers: {"Content-Type": "application/json"},
      body: JSON.stringify({cookies: cookies, ts: Date.now()})
    });
  } catch (e) { /* 忽略，脚本会超时报错 */ }
}
push();
chrome.runtime.onStartup.addListener(push);
chrome.runtime.onInstalled.addListener(push);
setTimeout(push, 2000);
setTimeout(push, 6000);
setTimeout(push, 12000);
"""


def keep(domain: str) -> bool:
    d = (domain or "").lower().lstrip(".")
    return any(k in d for k in KEEP_DOMAIN_KEYWORDS)


def write_netscape(cookies: list[dict], out: pathlib.Path) -> int:
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by tools/export_chrome_cookies_extension.py",
        "# 仅含 YouTube/Google 相关 cookie；请勿提交或分享",
        "",
    ]
    now = time.time()
    for c in cookies:
        domain = (c.get("domain") or "").strip()
        name = c.get("name") or ""
        if not domain or not name:
            continue
        flag = "TRUE" if domain.startswith(".") else "FALSE"
        prefix = "#HttpOnly_" if c.get("httpOnly") else ""
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = c.get("expirationDate")
        try:
            expires = int(float(expires)) if expires else 0
        except (TypeError, ValueError):
            expires = 0
        if 0 < expires < now:
            expires = 0  # 已过期则当会话 cookie 处理
        lines.append(
            f"{prefix}{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{c.get('value') or ''}"
        )
    tmp = out.with_suffix(out.suffix + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, out)
    try:
        os.chmod(out, 0o600)
    except OSError:
        pass
    return len(lines) - 4


class Collector(http.server.BaseHTTPRequestHandler):
    received: list[dict] | None = None
    done: threading.Event | None = None
    any_post = False
    post_count = 0

    def do_POST(self):
        try:
            length = int(self.headers.get("Content-Length", 0))
            payload = json.loads(self.rfile.read(length).decode("utf-8"))
            cookies = payload.get("cookies") or []
            Collector.any_post = True
            Collector.post_count += 1
            if len(cookies) > len(Collector.received or []):
                Collector.received = cookies
            if cookies:
                Collector.done.set()
            self.send_response(200)
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(b"ok")
        except Exception:
            self.send_response(400)
            self.end_headers()

    def log_message(self, *args):
        pass


def chrome_exe() -> str:
    candidates = [
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
        os.path.expandvars(r"%LOCALAPPDATA%\Google\Chrome\Application\chrome.exe"),
    ]
    for p in candidates:
        if os.path.isfile(p):
            return p
    raise RuntimeError("找不到 chrome.exe")


def current_profile(user_data: pathlib.Path) -> str:
    try:
        ls = json.loads((user_data / "Local State").read_text(encoding="utf-8"))
        return ls.get("profile", {}).get("last_used") or "Default"
    except Exception:
        return "Default"


def kill_chrome() -> None:
    subprocess.run(["taskkill", "/F", "/IM", "chrome.exe"], capture_output=True)
    time.sleep(2)


def launch_chrome(args: list[str]) -> int:
    p = subprocess.Popen(args, creationflags=0x00000008, close_fds=True)  # DETACHED_PROCESS
    return p.pid


def restore_chrome(exe: str) -> None:
    """用 ShellExecute 启动，彻底脱离当前命令会话（避免被作业对象回收）。"""
    try:
        os.startfile(exe, "open", "--restore-last-session")
        return
    except Exception:
        pass
    subprocess.Popen(
        [exe, "--restore-last-session"],
        creationflags=0x00000008 | 0x00000200,  # DETACHED | NEW_PROCESS_GROUP
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        close_fds=True,
    )


def diag_cookie_db(user_data: pathlib.Path, profile: str) -> None:
    """Chrome 关闭后只读诊断：确认登录态 cookie 确实写进了这个 profile。"""
    src = user_data / profile / "Network" / "Cookies"
    if not src.is_file():
        src = user_data / profile / "Cookies"
    if not src.is_file():
        print(f"[diag] 找不到 cookie 库：{src}")
        return
    dst = pathlib.Path(tempfile.gettempdir()) / "mkt_cookies_diag.db"
    try:
        shutil.copyfile(src, dst)
        con = sqlite3.connect(str(dst))
        cur = con.cursor()
        cur.execute("select count(*) from cookies")
        total = cur.fetchone()[0]
        cur.execute(
            "select host_key, name, substr(encrypted_value,1,3) from cookies "
            "where host_key like '%youtube%' or host_key like '%google%'"
        )
        rows = cur.fetchall()
        con.close()
        login = sorted({r[1] for r in rows if any(h in r[1] for h in LOGIN_COOKIE_HINTS)})
        enc = sorted({r[2].decode("latin1", "replace") for r in rows})
        print(f"[diag] {profile}: 总 cookie={total}，YouTube/Google={len(rows)}，加密前缀={enc}")
        print(f"[diag] 登录态 cookie 名：{login or '（未发现，可能未登录或登录态在别的 profile）'}")
    except Exception as exc:
        print(f"[diag] 诊断失败（不影响导出）：{type(exc).__name__}: {str(exc)[:150]}")


def verify(out: pathlib.Path, video_id: str) -> int:
    import yt_dlp

    print(f"[verify] 用 {out.name} 解析 https://www.youtube.com/watch?v={video_id} ...")
    try:
        with yt_dlp.YoutubeDL(
            {"quiet": True, "no_warnings": True, "noplaylist": True,
             "cookiefile": str(out), "socket_timeout": 30, "skip_download": True}
        ) as ydl:
            info = ydl.extract_info(f"https://www.youtube.com/watch?v={video_id}", download=False)
        print(f"[verify] 成功：{info.get('title')} | {info.get('duration')}s")
        return 0
    except Exception as exc:
        print(f"[verify] 解析失败：{str(exc)[:260]}", file=sys.stderr)
        return 1


def main() -> int:
    ap = argparse.ArgumentParser(description="用临时扩展在原始 Chrome profile 内导出 cookies")
    ap.add_argument("--profile", default=None, help='Chrome profile 目录名，默认读 Local State 的 last_used')
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--verify", action="store_true", help="导出后验证 YouTube 解析")
    ap.add_argument("--video-id", default="9E6b3swbnWg")
    ap.add_argument("--wait", type=int, default=30, help="等待扩展回传的秒数")
    ap.add_argument("--keep-open", action="store_true", help="结束后不恢复 Chrome（调试用）")
    args = ap.parse_args()

    out = pathlib.Path(args.out).expanduser()
    if not out.is_absolute():
        out = (BASE_DIR / out).resolve()

    user_data = pathlib.Path(os.environ.get("LOCALAPPDATA", "")) / "Google" / "Chrome" / "User Data"
    if not user_data.is_dir():
        print(f"找不到 Chrome 用户数据目录：{user_data}", file=sys.stderr)
        return 1
    profile = args.profile or current_profile(user_data)
    print(f"[ext] 使用 profile：{profile}")

    # 1) 起本机接收服务（端口由系统分配，避免冲突）
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Collector)
    port = server.server_address[1]
    Collector.received = None
    Collector.any_post = False
    Collector.post_count = 0
    Collector.done = threading.Event()
    threading.Thread(target=server.serve_forever, daemon=True).start()

    # 2) 生成临时扩展
    ext_dir = pathlib.Path(tempfile.gettempdir()) / "music-api-cookie-ext"
    if ext_dir.exists():
        shutil.rmtree(ext_dir, ignore_errors=True)
    ext_dir.mkdir(parents=True)
    (ext_dir / "manifest.json").write_text(json.dumps(MANIFEST, indent=2), encoding="utf-8")
    (ext_dir / "sw.js").write_text(
        SW_TEMPLATE.replace("__ENDPOINT__", f"http://127.0.0.1:{port}/cookies"),
        encoding="utf-8",
    )

    exe = chrome_exe()
    chrome_args = [
        exe,
        "--user-data-dir=" + str(user_data),
        "--profile-directory=" + profile,
        "--load-extension=" + str(ext_dir),
        "--disable-extensions-except=" + str(ext_dir),
        # Chrome 137+ 默认禁用 --load-extension，显式关掉该 feature
        "--disable-features=DisableLoadExtensionCommandLineSwitch",
        "--no-first-run",
        "--no-default-browser-check",
        "--restore-last-session",
    ]

    print("[ext] 关闭当前 Chrome（标签页稍后会恢复）...")
    kill_chrome()
    diag_cookie_db(user_data, profile)
    print(f"[ext] 用原始 profile 启动 Chrome 并加载临时扩展（接收端口 {port}）...")
    pid = launch_chrome(chrome_args)
    print(f"[ext] Chrome pid={pid}，等待扩展回传（最多 {args.wait}s）...")

    ok = Collector.done.wait(args.wait)
    server.shutdown()
    cookies = Collector.received or []
    print(f"[ext] 扩展回传 {Collector.post_count} 次，收到 {len(cookies)} 条 cookie")

    if not args.keep_open:
        print("[ext] 恢复用户原来的 Chrome（不带临时扩展）...")
        kill_chrome()
        restore_chrome(exe)
        print("[ext] Chrome 已恢复")

    if not ok or not cookies:
        reason = (
            "扩展已连通但 cookie 为空" if Collector.any_post
            else "扩展未连通（Chrome 137+ 需放行 --load-extension；或被安全策略拦截）"
        )
        print(f"[ext] 没有拿到 cookie：{reason}", file=sys.stderr)
        return 1

    selected = [c for c in cookies if keep(c.get("domain", ""))]
    login = sorted({c["name"] for c in selected if any(h in c["name"] for h in LOGIN_COOKIE_HINTS)})
    print(f"[ext] YouTube/Google 相关 {len(selected)} 条")
    print(f"[ext] 登录态 cookie 名：{login or '（未发现）'}")
    if not selected:
        print("[ext] 没有 YouTube 相关 cookie，请确认 Chrome 已登录 youtube.com", file=sys.stderr)
        return 1
    if not login:
        print("[ext] 警告：未发现登录态 cookie，导出的可能只是访客态（机器人校验仍会拦截）", file=sys.stderr)

    n = write_netscape(selected, out)
    print(f"[ext] 已写出 {n} 条 -> {out}")
    print(f"[ext] 涉及域名：{', '.join(sorted({c['domain'] for c in selected})[:12])}")

    if args.verify:
        return verify(out, args.video_id)
    print("\n下一步：在 .env 里设置 MUSIC_COOKIES_FILE=./data/cookies.txt 并重启 API。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""把本机 Chrome 的 YouTube 登录态导出成 Netscape cookies.txt，供 Music MP3 API 使用。

背景：Chrome（尤其 127+ 的 App-Bound Encryption）运行时会独占锁定 Cookies 数据库，
yt-dlp 的 --cookies-from-browser 无法复制（issue #7271）；CDP 又要求 Chrome 带
--remote-allow-origins 启动。因此提供两条通道：

  cdp     通过 Chrome DevTools Protocol 直接读取明文 cookie（推荐，不需要关闭 Chrome，
          但 Chrome 必须带 --remote-allow-origins=* 启动过一次）
  browser 让 yt-dlp 自己从浏览器 cookie 库读取（需要先完全关闭 Chrome，并安装
          pywin32 / cryptography 用于解密）

只导出 YouTube / Google 相关域名的 cookie，避免把全部站点登录态写进明文文件。
脚本不会打印任何 cookie 值。

用法：
  python tools/export_chrome_cookies.py --mode cdp
  python tools/export_chrome_cookies.py --mode browser --profile "Profile 12" --verify
  python tools/export_chrome_cookies.py --mode cdp --out data/cookies.txt --verify
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import pathlib
import sys
import time
import urllib.request

BASE_DIR = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUT = BASE_DIR / "data" / "cookies.txt"
KEEP_DOMAIN_KEYWORDS = (
    "youtube", "googlevideo", "ytimg", "google", "gstatic", "googleapis",
    "youtube-nocookie", "doubleclick",
)
ORIGIN_CANDIDATES = (
    None,
    "http://localhost:9222",
    "http://127.0.0.1:9222",
    "devtools://devtools",
    "chrome://devtools",
)


def chrome_user_data() -> pathlib.Path:
    local = os.environ.get("LOCALAPPDATA", "")
    return pathlib.Path(local) / "Google" / "Chrome" / "User Data"


def cdp_target(port: int | None) -> tuple[int, str, str | None]:
    """返回 (port, websocket path, error)。

    优先用 /json/version —— 它返回**当前实例**真实的 webSocketDebuggerUrl。
    DevToolsActivePort 可能残留上一次启动的 browser id，只作为端口来源与兜底。
    """
    from urllib.parse import urlparse

    fallback_path = ""
    p = chrome_user_data() / "DevToolsActivePort"
    if p.is_file():
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        if len(lines) >= 2 and lines[0].strip().isdigit():
            port = port or int(lines[0].strip())
            fallback_path = lines[1].strip()
    port = port or 9222

    try:
        # 用 http.client 直连，避免环境里的 http_proxy/https_proxy 把 localhost 请求转走
        import http.client

        conn = http.client.HTTPConnection("127.0.0.1", port, timeout=5)
        conn.request("GET", "/json/version")
        resp = conn.getresponse()
        ver = json.loads(resp.read().decode("utf-8", "replace"))
        conn.close()
        ws = ver.get("webSocketDebuggerUrl", "")
        if ws:
            return port, urlparse(ws).path or "/", None
    except Exception:
        pass

    if fallback_path:
        return port, fallback_path, None
    return port, "", (
        f"无法连接 127.0.0.1:{port} 的 DevTools 端点，说明 Chrome 没有开启远程调试端口。"
        "请用 --remote-debugging-port=9222 --remote-allow-origins=* 重新启动 Chrome。"
    )


def chrome_restart_hint() -> str:
    exe = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
    return (
        "Chrome 拒绝了 CDP 连接（Origin 校验）。需要用下面的参数重启一次 Chrome：\n"
        f'  "{exe}" --remote-debugging-port=9222 --remote-allow-origins=*\n'
        "注意：这会关闭当前所有 Chrome 窗口；Chrome 通常会自动恢复标签页，"
        "但未提交的表单内容可能丢失。重启后重新运行本脚本的 --mode cdp 即可。"
    )


def keep(domain: str) -> bool:
    d = (domain or "").lower().lstrip(".")
    return any(k in d for k in KEEP_DOMAIN_KEYWORDS)


def write_netscape(cookies: list[dict], out: pathlib.Path) -> int:
    """把 CDP cookie 列表写成 Netscape HTTP Cookie File 格式。"""
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by tools/export_chrome_cookies.py — 仅含 YouTube/Google 相关 cookie",
        "# 请勿提交到版本库或分享给他人",
        "",
    ]
    now = time.time()
    for c in cookies:
        domain = (c.get("domain") or "").strip()
        if not domain:
            continue
        flag = "TRUE" if domain.startswith(".") else "FALSE"
        prefix = "#HttpOnly_" if c.get("httpOnly") or c.get("httponly") else ""
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = c.get("expires") or -1
        try:
            expires = int(float(expires))
        except (TypeError, ValueError):
            expires = -1
        # 会话 cookie 或已过期的写 0；yt-dlp 仍会加载（ignore_discard）
        if expires <= 0 or expires < now:
            expires = 0
        name = c.get("name") or ""
        value = c.get("value") or ""
        if not name:
            continue
        lines.append(
            f"{prefix}{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}"
        )
    tmp = out.with_suffix(out.suffix + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, out)
    try:
        os.chmod(out, 0o600)
    except OSError:
        pass
    return len(lines) - 4


async def _cdp_fetch(port: int, ws_path: str) -> tuple[list[dict] | None, str | None]:
    try:
        import websockets
    except ImportError:
        return None, "缺少 websockets 库，请执行 pip install websockets"

    url = f"ws://127.0.0.1:{port}{ws_path}"
    for origin in ORIGIN_CANDIDATES:
        # proxy=None：websockets 17 默认 proxy=True 会自动套用环境代理，
        # 连 127.0.0.1 的 CDP 也会被转走并报 WinError 1225
        kwargs = {"max_size": 16 * 1024 * 1024, "open_timeout": 6, "proxy": None}
        if origin:
            kwargs["origin"] = origin
        try:
            async with websockets.connect(url, **kwargs) as ws:
                await ws.send(json.dumps({"id": 1, "method": "Storage.getCookies"}))
                while True:
                    msg = json.loads(await asyncio.wait_for(ws.recv(), timeout=12))
                    if msg.get("id") == 1:
                        if "error" in msg:
                            return None, f"CDP 错误：{msg['error']}"
                        return msg["result"]["cookies"], None
        except Exception as exc:
            last = f"{type(exc).__name__}: {str(exc)[:120]}"
            continue
    return None, f"{last}\n\n{chrome_restart_hint()}"


def mode_cdp(port: int | None, out: pathlib.Path) -> int:
    real_port, ws_path, err = cdp_target(port)
    if err:
        print(f"[cdp] {err}", file=sys.stderr)
        return 1
    if not ws_path:
        print(f"[cdp] 无法确定 WebSocket 路径：{err}", file=sys.stderr)
        return 1
    print(f"[cdp] 连接 127.0.0.1:{real_port}{ws_path[:40]}...")
    cookies, error = asyncio.run(_cdp_fetch(real_port, ws_path))
    if error or cookies is None:
        print(f"[cdp] 失败：\n{error}", file=sys.stderr)
        return 1
    selected = [c for c in cookies if keep(c.get("domain", ""))]
    print(f"[cdp] 读取到 {len(cookies)} 条 cookie，其中 YouTube/Google 相关 {len(selected)} 条")
    if not selected:
        print("[cdp] 没有找到 YouTube 相关 cookie，请确认 Chrome 里已登录 youtube.com", file=sys.stderr)
        return 1
    n = write_netscape(selected, out)
    domains = sorted({c["domain"] for c in selected})
    print(f"[cdp] 已写出 {n} 条 -> {out}")
    print(f"[cdp] 涉及域名：{', '.join(domains[:12])}")
    return 0


def mode_browser(browser: str, profile: str | None, out: pathlib.Path) -> int:
    try:
        import yt_dlp
    except ImportError:
        print("[browser] 缺少 yt-dlp，请执行 pip install -r requirements.txt", file=sys.stderr)
        return 1
    print(f"[browser] 从 {browser}:{profile or '默认配置'} 读取 cookie 库...")
    try:
        with yt_dlp.YoutubeDL(
            {"quiet": True, "no_warnings": True, "cookiesfrombrowser": (browser, profile, None, None)}
        ) as ydl:
            jar = ydl.cookiejar
            all_cookies = list(jar)
            # 只保留 YouTube / Google 相关，避免明文文件包含其它站点登录态
            for c in jar:
                if not keep(c.domain):
                    jar.clear(c.domain, c.path, c.name)
            out.parent.mkdir(parents=True, exist_ok=True)
            jar.save(str(out), ignore_discard=True, ignore_expires=True)
            try:
                os.chmod(out, 0o600)
            except OSError:
                pass
    except Exception as exc:
        print(f"[browser] 失败：{exc}", file=sys.stderr)
        print(
            "[browser] 常见原因：Chrome 仍在运行（cookie 库被独占锁定）、"
            "缺少 pywin32/cryptography 无法解密、profile 名称不对。\n"
            "          可执行 pip install pywin32 cryptography 后完全关闭 Chrome 再试，"
            "或改用 --mode cdp。",
            file=sys.stderr,
        )
        return 1
    kept = sum(1 for c in all_cookies if keep(c.domain))
    print(f"[browser] 读取到 {len(all_cookies)} 条，保留 YouTube/Google 相关 {kept} 条 -> {out}")
    return 0


def verify(out: pathlib.Path, video_id: str) -> int:
    """用导出的 cookies 真实解析一个 YouTube 视频，确认登录态有效。"""
    import yt_dlp

    print(f"[verify] 用 {out.name} 解析 https://www.youtube.com/watch?v={video_id} ...")
    opts = {
        "quiet": True,
        "no_warnings": True,
        "noplaylist": True,
        "cookiefile": str(out),
        "socket_timeout": 30,
        "skip_download": True,
    }
    try:
        with yt_dlp.YoutubeDL(opts) as ydl:
            info = ydl.extract_info(f"https://www.youtube.com/watch?v={video_id}", download=False)
        print(f"[verify] 成功：{info.get('title')}  |  {info.get('duration')}s")
        print("[verify] cookies 有效，可以把 MUSIC_COOKIES_FILE 指向该文件并重启 API。")
        return 0
    except Exception as exc:
        print(f"[verify] 解析失败：{str(exc)[:300]}", file=sys.stderr)
        print("[verify] 可能是 cookies 不完整/已过期、或仍被区域限制，请重新登录 YouTube 后再导出。", file=sys.stderr)
        return 1


def main() -> int:
    ap = argparse.ArgumentParser(description="导出 Chrome 的 YouTube cookies 为 Netscape cookies.txt")
    ap.add_argument("--mode", choices=("cdp", "browser"), default="cdp")
    ap.add_argument("--port", type=int, default=None, help="CDP 端口（默认从 DevToolsActivePort 读取）")
    ap.add_argument("--browser", default="chrome", help="browser 模式的浏览器名")
    ap.add_argument("--profile", default=None, help='browser 模式的 profile，例如 "Profile 12"')
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="输出 cookies.txt 路径")
    ap.add_argument("--verify", action="store_true", help="导出后用 yt-dlp 验证能否解析 YouTube 视频")
    ap.add_argument("--video-id", default="9E6b3swbnWg", help="验证用的视频 ID")
    args = ap.parse_args()

    out = pathlib.Path(args.out).expanduser()
    if not out.is_absolute():
        out = (BASE_DIR / out).resolve()

    rc = mode_cdp(args.port, out) if args.mode == "cdp" else mode_browser(args.browser, args.profile, out)
    if rc != 0:
        return rc
    if args.verify:
        return verify(out, args.video_id)
    print("\n下一步：在 .env 里设置 MUSIC_COOKIES_FILE=./data/cookies.txt 并重启 API。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

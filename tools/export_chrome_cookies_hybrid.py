"""在原 Chrome profile 下同时尝试两条明文 cookie 通道，导出 Netscape cookies.txt。

背景：Chrome 127+ 的 App-Bound Encryption（v20）把 cookie 加密绑定到原 profile
环境。yt-dlp 解不开；复制 profile / 目录联接后 Chrome 自己也会丢弃 v20 cookie。
因此必须让**原始 profile 下的 Chrome 自己**解密并输出明文。

本脚本一次重启同时尝试：

  A) CDP：--remote-debugging-port + Storage.getCookies
     Chrome 136+ 拒绝在默认 user-data-dir 上开调试端口；这里用同一目录的
     8.3 短路径名绕过字符串比较，实际仍是原目录，App-Bound 仍可解密。
  B) 临时扩展：--load-extension + chrome.cookies.getAll()（Chrome 内部解密）
     同时开启 PNA 预检与错误上报，便于定位。

任一通道拿到登录态 cookie 即写出 cookies.txt，并用 yt-dlp 验证真实 YouTube 解析。

用法：
  python tools/export_chrome_cookies_hybrid.py --verify
  python tools/export_chrome_cookies_hybrid.py --profile "Profile 12" --verify
"""
from __future__ import annotations

import argparse
import asyncio
import ctypes
import http.server
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import threading
import time
import urllib.request

BASE_DIR = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUT = BASE_DIR / "data" / "cookies.txt"
KEEP_DOMAIN_KEYWORDS = (
    "youtube", "googlevideo", "ytimg", "google", "gstatic", "googleapis",
    "youtube-nocookie", "doubleclick",
)
LOGIN_COOKIE_HINTS = (
    "SAPISID", "1PSID", "3PSID", "APISID", "HSID", "SSID", "SIDCC",
    "LOGIN_INFO", "1PAPISID", "3PAPISID",
)

MANIFEST = {
    "manifest_version": 3,
    "name": "Music API Cookie Exporter (temporary)",
    "version": "1.0",
    "description": "Temporary local helper that exports YouTube cookies to the local API.",
    "permissions": ["cookies"],
    "host_permissions": ["<all_urls>"],
    "background": {"service_worker": "sw.js"},
}

SW_TEMPLATE = """
const ENDPOINT = "__ENDPOINT__";
async function post(obj) {
  try {
    await fetch(ENDPOINT, {
      method: "POST",
      headers: {"Content-Type": "application/json"},
      body: JSON.stringify(obj)
    });
  } catch (e) { /* 无法上报 */ }
}
async function push() {
  try {
    await post({ping: true});
    const cookies = await chrome.cookies.getAll({});
    await post({cookies: cookies, ts: Date.now()});
  } catch (e) {
    await post({error: String(e)});
  }
}
push();
chrome.runtime.onInstalled.addListener(push);
chrome.runtime.onStartup.addListener(push);
setTimeout(push, 3000);
setTimeout(push, 9000);
"""


# --------------------------------------------------------------------------- 工具

def keep(domain: str) -> bool:
    d = (domain or "").lower().lstrip(".")
    return any(k in d for k in KEEP_DOMAIN_KEYWORDS)


def is_login(name: str) -> bool:
    return any(h in (name or "") for h in LOGIN_COOKIE_HINTS)


def write_netscape(cookies: list[dict], out: pathlib.Path) -> int:
    """接受 CDP 格式或 chrome.cookies 格式（字段名自动兼容）。"""
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by tools/export_chrome_cookies_hybrid.py",
        "# 仅含 YouTube/Google 相关 cookie；请勿提交或分享",
        "",
    ]
    now = time.time()
    for c in cookies:
        domain = (c.get("domain") or "").strip()
        name = c.get("name") or ""
        if not domain or not name:
            continue
        flag = "TRUE" if domain.startswith(".") else "FALSE"
        http_only = c.get("httpOnly", c.get("httponly", False))
        prefix = "#HttpOnly_" if http_only else ""
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        raw_exp = c.get("expires", c.get("expirationDate"))
        try:
            expires = int(float(raw_exp)) if raw_exp else 0
        except (TypeError, ValueError):
            expires = 0
        if expires and expires < now:
            expires = 0
        lines.append(
            f"{prefix}{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{c.get('value') or ''}"
        )
    tmp = out.with_suffix(out.suffix + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, out)
    try:
        os.chmod(out, 0o600)
    except OSError:
        pass
    return len(lines) - 4


def chrome_exe() -> str:
    for p in (
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
        os.path.expandvars(r"%LOCALAPPDATA%\Google\Chrome\Application\chrome.exe"),
    ):
        if os.path.isfile(p):
            return p
    raise RuntimeError("找不到 chrome.exe")


def user_data_dir() -> pathlib.Path:
    return pathlib.Path(os.environ.get("LOCALAPPDATA", "")) / "Google" / "Chrome" / "User Data"


def short_path(p: pathlib.Path) -> str:
    """取 8.3 短路径名：字符串与默认目录不同，但指向同一目录。"""
    buf = ctypes.create_unicode_buffer(2048)
    r = ctypes.windll.kernel32.GetShortPathNameW(str(p), buf, 2048)
    return buf.value if r and buf.value else str(p)


def current_profile(base: pathlib.Path) -> str:
    try:
        ls = json.loads((base / "Local State").read_text(encoding="utf-8"))
        return ls.get("profile", {}).get("last_used") or "Default"
    except Exception:
        return "Default"


def kill_chrome() -> None:
    subprocess.run(["taskkill", "/F", "/IM", "chrome.exe"], capture_output=True)
    time.sleep(2)


def backup_profile(base: pathlib.Path, profile: str, backup_dir: pathlib.Path) -> None:
    """Chrome 关闭后备份 cookie 库与 Local State；万一启动后登录态被清可原样恢复。"""
    try:
        backup_dir.mkdir(parents=True, exist_ok=True)
        pairs = [
            (base / profile / "Network" / "Cookies", backup_dir / "Cookies"),
            (base / "Local State", backup_dir / "Local State"),
        ]
        for src, dst in pairs:
            if src.is_file():
                shutil.copyfile(src, dst)
        print(f"[backup] 已备份 cookie 库与 Local State -> {backup_dir}")
    except Exception as exc:
        print(f"[backup] 备份失败（继续）：{type(exc).__name__}: {str(exc)[:120]}")


def launch(args: list[str]) -> int:
    p = subprocess.Popen(args, creationflags=0x00000008, close_fds=True)
    return p.pid


def restore_chrome(exe: str) -> None:
    try:
        os.startfile(exe, "open", "--restore-last-session")
        return
    except Exception:
        pass
    subprocess.Popen(
        [exe, "--restore-last-session"],
        creationflags=0x00000008 | 0x00000200,
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        close_fds=True,
    )


# --------------------------------------------------------------------------- 通道 B：扩展

class Collector(http.server.BaseHTTPRequestHandler):
    best: list[dict] = []
    errors: list[str] = []
    pings = 0
    posts = 0
    done: threading.Event | None = None

    def do_OPTIONS(self):
        # Chrome Private Network Access 预检
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "*")
        self.send_header("Access-Control-Allow-Private-Network", "true")
        self.end_headers()

    def do_POST(self):
        try:
            length = int(self.headers.get("Content-Length", 0))
            payload = json.loads(self.rfile.read(length).decode("utf-8"))
            Collector.posts += 1
            if payload.get("ping"):
                Collector.pings += 1
            if payload.get("error"):
                Collector.errors.append(str(payload["error"])[:200])
            cookies = payload.get("cookies") or []
            if len(cookies) > len(Collector.best):
                Collector.best = cookies
                Collector.done.set()
            self.send_response(200)
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(b"ok")
        except Exception:
            self.send_response(400)
            self.end_headers()

    def log_message(self, *args):
        pass


def make_extension(ext_dir: pathlib.Path, port: int) -> None:
    if ext_dir.exists():
        shutil.rmtree(ext_dir, ignore_errors=True)
    ext_dir.mkdir(parents=True)
    (ext_dir / "manifest.json").write_text(json.dumps(MANIFEST, indent=2), encoding="utf-8")
    (ext_dir / "sw.js").write_text(
        SW_TEMPLATE.replace("__ENDPOINT__", f"http://127.0.0.1:{port}/cookies"),
        encoding="utf-8",
    )


# --------------------------------------------------------------------------- 通道 A：CDP

def cdp_cookies(port: int, timeout: float = 12.0) -> tuple[list[dict], str]:
    """返回 (cookies, 诊断信息)。必须 proxy=None，否则本机 WS 会被环境代理拦掉。"""
    import websockets

    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    try:
        ver = json.load(opener.open(f"http://127.0.0.1:{port}/json/version", timeout=5))
    except Exception as exc:
        return [], f"/json/version 不可达：{type(exc).__name__}: {str(exc)[:120]}"
    ws_url = ver.get("webSocketDebuggerUrl", "")
    if not ws_url:
        return [], "缺少 webSocketDebuggerUrl"

    async def call():
        for origin in (None, "http://localhost:9222", "http://127.0.0.1:9222"):
            kw = {"proxy": None, "max_size": 32 * 1024 * 1024, "open_timeout": 5}
            if origin:
                kw["origin"] = origin
            try:
                async with websockets.connect(ws_url, **kw) as ws:
                    await ws.send(json.dumps({"id": 1, "method": "Storage.getCookies"}))
                    msg = json.loads(await asyncio.wait_for(ws.recv(), timeout=timeout))
                    if "error" in msg:
                        return [], f"CDP error: {msg['error']}"
                    return msg["result"]["cookies"], "ok"
            except Exception as exc:
                last = f"{type(exc).__name__}: {str(exc)[:120]}"
        return [], last or "unknown"

    return asyncio.run(call())


# --------------------------------------------------------------------------- 主流程

def verify(out: pathlib.Path, video_id: str) -> int:
    import yt_dlp

    print(f"[verify] 用 {out.name} 解析 https://www.youtube.com/watch?v={video_id} ...")
    try:
        with yt_dlp.YoutubeDL(
            {"quiet": True, "no_warnings": True, "noplaylist": True,
             "cookiefile": str(out), "socket_timeout": 30, "skip_download": True}
        ) as ydl:
            info = ydl.extract_info(f"https://www.youtube.com/watch?v={video_id}", download=False)
        print(f"[verify] 成功：{info.get('title')} | {info.get('duration')}s")
        return 0
    except Exception as exc:
        print(f"[verify] 解析失败：{str(exc)[:260]}", file=sys.stderr)
        return 1


def main() -> int:
    ap = argparse.ArgumentParser(description="原 profile 双通道导出 Chrome cookies")
    ap.add_argument("--profile", default=None)
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--video-id", default="9E6b3swbnWg")
    ap.add_argument("--wait", type=int, default=20, help="等待扩展回传的秒数")
    ap.add_argument("--port", type=int, default=9222, help="CDP 调试端口")
    ap.add_argument("--original-dir", action="store_true", help="用原始目录而非短路径（诊断用）")
    ap.add_argument("--keep-open", action="store_true")
    args = ap.parse_args()

    out = pathlib.Path(args.out).expanduser()
    if not out.is_absolute():
        out = (BASE_DIR / out).resolve()

    base = user_data_dir()
    profile = args.profile or current_profile(base)
    exe = chrome_exe()
    launch_dir = str(base) if args.original_dir else short_path(base)
    print(f"[hybrid] profile={profile}")
    print(f"[hybrid] user-data-dir={launch_dir}")

    # 接收服务 + 临时扩展
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Collector)
    cport = server.server_address[1]
    Collector.best = []
    Collector.errors = []
    Collector.pings = 0
    Collector.posts = 0
    Collector.done = threading.Event()
    threading.Thread(target=server.serve_forever, daemon=True).start()
    ext_dir = pathlib.Path(tempfile.gettempdir()) / "music-api-cookie-ext"
    make_extension(ext_dir, cport)

    chrome_args = [
        exe,
        "--user-data-dir=" + launch_dir,
        "--profile-directory=" + profile,
        "--remote-debugging-port=" + str(args.port),
        "--remote-allow-origins=*",
        "--load-extension=" + str(ext_dir),
        "--disable-extensions-except=" + str(ext_dir),
        "--disable-features=DisableLoadExtensionCommandLineSwitch",
        "--no-first-run",
        "--no-default-browser-check",
        "--restore-last-session",
    ]

    print("[hybrid] 关闭当前 Chrome（标签页稍后恢复）...")
    kill_chrome()
    backup_profile(base, profile, BASE_DIR / "data" / "_profile_backup")
    print("[hybrid] 启动 Chrome（CDP + 临时扩展）...")
    pid = launch(chrome_args)
    print(f"[hybrid] Chrome pid={pid}，等待 {args.wait}s ...")

    # 先给 Chrome 一点启动时间，然后同时跑 CDP 与扩展收集
    time.sleep(5)
    cdp_list, cdp_msg = cdp_cookies(args.port)
    print(f"[CDP ] cookies={len(cdp_list)}  {cdp_msg}")
    Collector.done.wait(args.wait)
    server.shutdown()
    print(
        f"[EXT ] posts={Collector.posts} pings={Collector.pings} "
        f"cookies={len(Collector.best)} errors={Collector.errors[:3] or '无'}"
    )

    if not args.keep_open:
        print("[hybrid] 恢复用户原来的 Chrome（不带调试端口/临时扩展）...")
        kill_chrome()
        restore_chrome(exe)
        print("[hybrid] Chrome 已恢复")

    # 选 cookie 更多、且含登录态的那一路
    candidates = []
    for label, ck in (("CDP", cdp_list), ("扩展", Collector.best)):
        if not ck:
            continue
        sel = [c for c in ck if keep(c.get("domain", ""))]
        login = sorted({c.get("name", "") for c in sel if is_login(c.get("name", ""))})
        print(f"[hybrid] {label}: 相关 {len(sel)} 条，登录态 {login or '（无）'}")
        candidates.append((bool(login), len(sel), label, sel))

    if not candidates:
        print("[hybrid] 两条通道都没拿到 cookie。", file=sys.stderr)
        return 1
    candidates.sort(reverse=True)
    has_login, _, label, selected = candidates[0]
    if not has_login:
        print("[hybrid] 警告：拿到的 cookie 不含登录态，YouTube 机器人校验可能仍会拦截", file=sys.stderr)

    n = write_netscape(selected, out)
    print(f"[hybrid] 采用 {label} 通道，写出 {n} 条 -> {out}")
    print(f"[hybrid] 域名：{', '.join(sorted({c['domain'] for c in selected})[:12])}")

    if args.verify:
        return verify(out, args.video_id)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
